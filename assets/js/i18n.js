const SUPPORTED_LANGS = Object.keys(translations);

function detectLanguage() {
    let saved = null;
    try {
        saved = localStorage.getItem('language');
    } catch (e) { /* storage unavailable */ }
    if (SUPPORTED_LANGS.includes(saved)) return saved;
    return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

let currentLang = detectLanguage();

function setLanguage(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) return;
    currentLang = lang;
    try {
        localStorage.setItem('language', lang);
    } catch (e) { /* storage unavailable */ }
    translatePage();
}

function translatePage() {
    const dict = translations[currentLang];
    document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en';
    document.title = dict.welcome;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        const text = dict[key] ?? translations.en[key];
        if (typeof text === 'string') element.textContent = text;
    });
    document.querySelectorAll('a.resume-link').forEach(link => {
        link.setAttribute('href', 'assets/resume/Jiashao-Chen-Resume-' + currentLang + '.pdf');
    });
    if (typeof window.initTyped === 'function') {
        window.initTyped(dict.heroRoles);
    }
}

document.addEventListener('DOMContentLoaded', translatePage);
